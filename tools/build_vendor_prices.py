"""Builds CueTheCashier/VendorPrices.lua: the base vendor buy price (no
discounts) of every reagent used by a profession recipe, from the game's
own data tables as published by wago.tools.

Usage: python3 build_vendor_prices.py <folder with the CSVs> <output .lua> [build]
The folder needs ItemSparse.csv, SpellReagents.csv and SkillLineAbility.csv,
downloaded from https://wago.tools/db2/<Table>/csv?build=<build>.

The game data gives every item a buy price, even items no vendor sells
(leather, ore). So the table has two parts:
  CM.VendorBuy[itemID]  = base price per single item (copper; may have
                          decimals when a vendor sells a bundle, e.g. 5
                          vials for 20c = 4c each)
  CM.VendorSold[itemID] = true for reagents we know vendors sell. The addon
                          adds more when you see them at a merchant.
"""
import csv, sys, datetime

# Profession skill lines (SkillLine table): First Aid, Blacksmithing,
# Leatherworking, Alchemy, Cooking, Mining, Tailoring, Engineering,
# Enchanting, plus the gathering skills that have recipe windows on
# Forever: Herbalism (Gardening), Fishing (Bait and Tackle), Skinning
# (Tanning).
PROFESSIONS = {"129", "164", "165", "171", "182", "185", "186", "197", "202", "333", "356", "393"}

# Reagents known to be sold by vendors in the 2004-era game, by name.
KNOWN_VENDOR = [
    "Coarse Thread", "Fine Thread", "Silken Thread", "Heavy Silken Thread", "Rune Thread",
    "Empty Vial", "Leaded Vial", "Crystal Vial", "Imbued Vial",
    "Gray Dye", "Blue Dye", "Red Dye", "Green Dye", "Black Dye", "Purple Dye", "Orange Dye",
    "Yellow Dye", "Pink Dye", "Bleach",
    "Weak Flux", "Strong Flux", "Salt",
    "Mild Spices", "Hot Spices", "Soothing Spices", "Ice Cold Milk", "Refreshing Spring Water",
    "Simple Wood", "Copper Rod",
]


def main(folder, out, build):
    rows = lambda name: csv.DictReader(open(f"{folder}/{name}.csv", encoding="utf-8"))
    spells = {r["Spell"] for r in rows("SkillLineAbility") if r["SkillLine"] in PROFESSIONS}
    reagents = set()
    for r in rows("SpellReagents"):
        if r["SpellID"] in spells:
            for i in range(8):
                rid = r[f"Reagent_{i}"]
                if rid and rid != "0":
                    reagents.add(rid)
    items = {r["ID"]: r for r in rows("ItemSparse")}
    buy, names = {}, {}
    for rid in reagents:
        it = items.get(rid)
        if not it:
            continue  # not in this game version
        price, bundle = int(it["BuyPrice"] or 0), max(int(it["VendorStackCount"] or 1), 1)
        if price > 0:
            unit = price / bundle
            buy[int(rid)] = int(unit) if unit == int(unit) else round(unit, 2)
            names[int(rid)] = it["Display_lang"]
    by_name = {}
    for i, n in names.items():
        by_name.setdefault(n, []).append(i)
    sold, missing = [], []
    for n in KNOWN_VENDOR:
        if n in by_name:
            sold.extend(by_name[n])
        else:
            missing.append(n)
    with open(out, "w", encoding="utf-8") as f:
        f.write("-- CueTheCashier: base vendor buy prices of profession reagents.\n")
        f.write(f"-- Generated by tools/build_vendor_prices.py from the game data of build {build}\n")
        f.write(f"-- (wago.tools) on {datetime.date.today()}. Do not edit by hand; run the script again.\n")
        f.write("-- VendorBuy: copper per single item, before any discount.\n")
        f.write("-- VendorSold: reagents known to be sold by vendors (the addon adds\n")
        f.write("-- more when you see them at a merchant).\n")
        f.write("-- Copyright (C) 2026 Kim. Licensed under the GNU GPL v3 or later; see LICENSE.\n")
        f.write("local _, CM = ...\n\nCM.VendorBuy = {\n")
        for i in sorted(buy):
            f.write(f"  [{i}] = {buy[i]}, -- {names[i]}\n")
        f.write("}\n\nCM.VendorSold = {\n")
        for i in sorted(sold):
            f.write(f"  [{i}] = true, -- {names[i]}\n")
        f.write("}\n")
    print(f"{len(spells)} recipe spells, {len(reagents)} reagents, {len(buy)} with a price, "
          f"{len(sold)} known vendor items.")
    if missing:
        print("Known vendor names not found among reagents:", ", ".join(missing))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else "?")
